def flatten():
    """Assign contiguous IDs, skipping reserved 20/77/78, then inject reserved rows."""
    provisional = []
    for s in SECTIONS:
        for cat, name, reason, signal in s["items"]:
            if (cat, name) in SKIP_AS_RESERVED:
                continue
            provisional.append({
                "section": s["num"],
                "section_title": s["title"],
                "family": s["family"],
                "category": cat,
                "name": name,
                "reason": reason,
                "signal": signal,
            })

    reserved = set(RESERVED_CRASH_NOS.keys())
    rows = []
    n = 0
    for item in provisional:
        n += 1
        while n in reserved:
            n += 1
        rows.append({**item, "no": n})

    for no, meta in RESERVED_CRASH_NOS.items():
        rows.append({"no": no, **meta})

    rows.sort(key=lambda r: r["no"])

    # Recompute section ranges from assigned rows
    by_sec = {}
    for r in rows:
        by_sec.setdefault(r["section"], []).append(r["no"])
    for s in SECTIONS:
        nos = by_sec.get(s["num"], [])
        if not nos and s["num"] == 5:
            # Crash types section also owns reserved 20/77/78
            nos = [20, 77, 78] + by_sec.get(5, [])
            nos = sorted(set(nos))
        if nos:
            s["id_start"] = min(nos)
            s["id_end"] = max(nos)
            s["count"] = len([r for r in rows if r["section"] == s["num"]])
        else:
            s["id_start"] = 0
            s["id_end"] = 0
            s["count"] = 0
    # Fix section 5 count to include reserved
    for s in SECTIONS:
        if s["num"] == 5:
            s["count"] = len([r for r in rows if r["section"] == 5])
            nos = [r["no"] for r in rows if r["section"] == 5]
            s["id_start"] = min(nos)
            s["id_end"] = max(nos)
    return rows


