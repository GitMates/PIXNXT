def build_taxonomy_js(rows: list[dict]):
    max_no = max(r["no"] for r in rows)
    lines = [
        f"// AUTO-GENERATED from Master Crash Report 1-{max_no}. Do not hand-edit.",
        f"// Stable instrumentation IDs: 20=ErrorBoundary, 77=window.onerror, 78=unhandledrejection.",
        f"export const CRASH_TOTAL = {len(rows)};",
        "export const CRASH_NO = Object.freeze({ ERROR_BOUNDARY: 20, UNHANDLED_EXCEPTION: 77, UNHANDLED_REJECTION: 78 });",
        "export const CRASH_LIST = [",
    ]
    for row in sorted(rows, key=lambda r: r["no"]):
        obj = {
            "no": row["no"],
            "category": row["category"],
            "name": row["name"],
            "reason": row["reason"],
            "signal": row["signal"],
            "section": row.get("section"),
            "sectionTitle": row.get("section_title"),
        }
        lines.append("  " + json.dumps(obj, ensure_ascii=False) + ",")
    lines.append("];")
    # Sections index for Admin UI (mirrors Word document dashboard)
    sec_objs = []
    for s in SECTIONS:
        sec_objs.append({
            "num": s["num"],
            "title": s["title"],
            "focus": s["focus"],
            "family": s["family"],
            "count": s.get("count", 0),
            "idStart": s.get("id_start", 0),
            "idEnd": s.get("id_end", 0),
        })
    lines.append(f"export const CRASH_SECTIONS = {json.dumps(sec_objs, ensure_ascii=False)};")
    lines.append(
        'export const crashByNo = (no) => CRASH_LIST.find((c)=>c.no===Number(no)) || '
        '{no,category:"Unknown",name:"Unknown crash",reason:"Unmapped",signal:"",section:null,sectionTitle:""};'
    )
    lines.append("export const CRASH_CATEGORIES = [...new Set(CRASH_LIST.map((c)=>c.category))];")
    lines.append(
        "function findCrashNo(pred) {\n"
        "  const hit = CRASH_LIST.find(pred);\n"
        "  return hit ? hit.no : null;\n"
        "}\n"
        "export function crashNoForApiError(err) {\n"
        "  const status = Number(err?.status ?? err?.statusCode ?? 0);\n"
        "  const code = String(err?.code || '');\n"
        "  const msg = String(err?.message || err || '');\n"
        "  if (status === 401 || code === 'UNAUTHORIZED' || /authentication required|session expired/i.test(msg))\n"
        "    return findCrashNo((c) => c.category === 'API' && /^401/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 403 || code === 'FORBIDDEN' || code === 'FORBIDDEN_PATH')\n"
        "    return findCrashNo((c) => c.category === 'API' && /^403/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 404 || code === 'NOT_FOUND' || /not found/i.test(msg))\n"
        "    return findCrashNo((c) => c.category === 'API' && /^404/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 413 || /too large|file too large/i.test(msg))\n"
        "    return findCrashNo((c) => c.category === 'API' && /413|80MB/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 429 || code === 'RATE_LIMITED' || /too many/i.test(msg))\n"
        "    return findCrashNo((c) => c.category === 'API' && /429/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 409 || code === 'CONFLICT' || /already exists/i.test(msg))\n"
        "    return findCrashNo((c) => c.category === 'CRUD-POST' && /409|CONFLICT/i.test(c.name))\n"
        "      || findCrashNo((c) => /UNIQUE|already exists|CONFLICT/i.test(c.name) && c.category.startsWith('CRUD'))\n"
        "      || findCrashNo((c) => c.category === 'API' && /409/.test(c.name))\n"
        "      || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status === 410 || code === 'EXPIRED')\n"
        "    return findCrashNo((c) => /EXPIRED token|Download-410/i.test(c.category + ' ' + c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (status >= 500)\n"
        "    return findCrashNo((c) => c.category === 'API' && /^500/.test(c.name)) || CRASH_NO.UNHANDLED_REJECTION;\n"
        "  if (err?.name === 'ApiError' || status >= 400) return CRASH_NO.UNHANDLED_REJECTION;\n"
        "  return CRASH_NO.UNHANDLED_REJECTION;\n"
        "}"
    )
    lines.append("")
    OUT_TAX.write_text("\n".join(lines), encoding="utf-8")
    return OUT_TAX


def main():
    rows = flatten()
    max_no = max(r["no"] for r in rows)
    assert len(rows) == len({r["no"] for r in rows}), "duplicate crash numbers"
    assert 20 in {r["no"] for r in rows} and crash_name(rows, 20)
    assert crash_name(rows, 77) == "Unhandled exception"
    assert crash_name(rows, 78) == "Unhandled rejection"
    if max_no > 1000:
        raise SystemExit(f"crash-reporter only accepts crashNo 1-1000; max={max_no}")
    docx_path = build_docx(rows)
    tax_path = build_taxonomy_js(rows)
    print(f"Wrote {len(rows)} crashes (max No. {max_no})")
    print(f"  reserved: 20={crash_name(rows,20)!r}  77={crash_name(rows,77)!r}  78={crash_name(rows,78)!r}")
    print(f"  docx: {docx_path}")
    print(f"  tax : {tax_path}")
    print("Sections:")
    for s in SECTIONS:
        print(f"  {s['num']:2d}  {s['count']:3d}  {s['id_start']:>3d}–{s['id_end']:<3d}  {s['title']}")


def crash_name(rows, no):
    for r in rows:
        if r["no"] == no:
            return r["name"]
    return None


if __name__ == "__main__":
    main()
